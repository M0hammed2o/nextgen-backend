"""
Orders — the core transactional entity.
Includes order items (snapshots at time of order) and audit events.
"""

import uuid
from datetime import datetime

from sqlalchemy import Boolean, DateTime, ForeignKey, Integer, String, Text, UniqueConstraint
from sqlalchemy.dialects.postgresql import JSONB, UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from shared.models.base import Base, TimestampMixin, UUIDPrimaryKeyMixin


class Order(Base, UUIDPrimaryKeyMixin, TimestampMixin):
    __tablename__ = "orders"

    # order_number is human-friendly (BO-000123) and only meaningful scoped
    # to one business — enforced in the DB (migration 0033) since two
    # concurrent order-number-sequence increments must never be able to
    # produce a duplicate for the same tenant.
    __table_args__ = (
        UniqueConstraint(
            "business_id", "order_number", name="uq_orders_business_id_order_number"
        ),
    )

    business_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), ForeignKey("businesses.id", ondelete="CASCADE"),
        nullable=False, index=True,
    )
    customer_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True), ForeignKey("customers.id", ondelete="SET NULL"),
        nullable=True, index=True,
    )

    # ── Order Number (human-friendly, unique per business) ───────────────
    order_number: Mapped[str] = mapped_column(
        String(32), nullable=False,
        comment="Human-friendly: BO-000123"
    )

    # ── Status ───────────────────────────────────────────────────────────
    status: Mapped[str] = mapped_column(
        String(32), default="NEW", nullable=False, index=True
    )
    payment_status: Mapped[str] = mapped_column(
        String(32), default="PENDING", nullable=False,
        comment="UNPAID / PENDING / PAID / FAILED / REFUNDED / PARTIALLY_REFUNDED / VOIDED / CASH_ON_COLLECTION"
    )

    # ── Order Details ────────────────────────────────────────────────────
    order_mode: Mapped[str] = mapped_column(
        String(32), default="PICKUP", nullable=False,
        comment="PICKUP / DELIVERY / DINE_IN"
    )
    source: Mapped[str] = mapped_column(
        String(32), default="WHATSAPP", nullable=False,
        comment="WHATSAPP / MANUAL / ADMIN / POS / UBER_EATS / MR_D / OTHER_EXTERNAL — see shared.enums.OrderSource"
    )

    # ── Money (cents) ────────────────────────────────────────────────────
    subtotal_cents: Mapped[int] = mapped_column(Integer, default=0, nullable=False)
    delivery_fee_cents: Mapped[int] = mapped_column(Integer, default=0, nullable=False)
    total_cents: Mapped[int] = mapped_column(Integer, default=0, nullable=False)
    currency: Mapped[str] = mapped_column(String(3), default="ZAR", nullable=False)

    # ── Customer Info (snapshot) ─────────────────────────────────────────
    customer_name: Mapped[str | None] = mapped_column(String(255), nullable=True)
    phone_number: Mapped[str | None] = mapped_column(String(32), nullable=True)
    delivery_address: Mapped[str | None] = mapped_column(Text, nullable=True)

    # ── Timestamps ───────────────────────────────────────────────────────
    estimated_ready_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True
    )
    confirmed_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True
    )
    accepted_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True
    )
    ready_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True
    )
    completed_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True
    )

    # ── Payment ──────────────────────────────────────────────────────────
    payment_required: Mapped[bool] = mapped_column(
        Boolean, default=False, nullable=False,
        comment="Snapshot of business.online_payment_required at order creation time"
    )
    payment_method: Mapped[str | None] = mapped_column(
        String(32), nullable=True,
        comment="CASH | CARD | PAY_ON_COLLECTION | DIRECT_EFT | PAYSHAP | YOCO | PAYFAST | STITCH"
    )
    payment_link_url: Mapped[str | None] = mapped_column(
        String(1024), nullable=True,
        comment="Payment link URL generated by provider (Yoco, PayFast, Stitch)"
    )
    payment_reference: Mapped[str | None] = mapped_column(
        String(255), nullable=True,
        comment="Card/EFT transaction reference, printed receipt number, etc."
    )
    paid_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True,
        comment="UTC timestamp when payment_status was set to PAID"
    )
    refund_reference: Mapped[str | None] = mapped_column(
        String(255), nullable=True,
        comment="Provider's own refund transaction id, distinct from payment_reference (the original charge)"
    )
    refund_amount_cents: Mapped[int | None] = mapped_column(
        Integer, nullable=True,
        comment="Amount actually refunded — may be less than total_cents for a partial refund"
    )
    refunded_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True,
        comment="UTC timestamp when the refund was recorded"
    )

    # ── Special Instructions ─────────────────────────────────────────────
    special_instructions: Mapped[str | None] = mapped_column(Text, nullable=True)

    # ── Cancellation ─────────────────────────────────────────────────────
    cancelled_reason: Mapped[str | None] = mapped_column(Text, nullable=True)
    cancelled_by_user_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True), nullable=True
    )

    # ── POS discount / tax (Phase 1) ─────────────────────────────────────
    discount_cents: Mapped[int] = mapped_column(Integer, default=0, nullable=False)
    tax_cents: Mapped[int] = mapped_column(Integer, default=0, nullable=False)
    discount_reason: Mapped[str | None] = mapped_column(Text, nullable=True)
    discount_approved_by_user_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True), nullable=True,
        comment="business_users.id who approved a staff discount above the "
                 "configured limit — not FK-enforced, same pattern as cancelled_by_user_id"
    )

    # ── POS checkout (Phase 2 — atomic pay-at-till) ──────────────────────
    table_number: Mapped[str | None] = mapped_column(
        String(32), nullable=True, comment="DINE_IN order_mode only"
    )
    cash_tendered_cents: Mapped[int | None] = mapped_column(
        Integer, nullable=True, comment="CASH payment_method only"
    )
    change_due_cents: Mapped[int | None] = mapped_column(
        Integer, nullable=True, comment="cash_tendered_cents - total_cents"
    )
    till_session_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True), ForeignKey("till_sessions.id", ondelete="SET NULL"),
        nullable=True, index=True,
        comment="Which till session rang this sale up — POS orders only"
    )
    # ── External marketplace channel (Uber Eats / Mr D / generic) ────────
    # An imported sale is a real Order, so it resolves the same recipes and
    # posts to the same ledger as a till sale. These columns carry only what
    # a till sale has no equivalent of.
    external_order_id: Mapped[str | None] = mapped_column(
        String(128), nullable=True,
        comment="The platform's own order id. Together with business_id and "
                "source this is the duplicate-upload guard (partial unique index)."
    )
    external_batch_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True), nullable=True,
        comment="external_import_batches.id — which uploaded file created this"
    )
    external_placed_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True,
        comment="When the customer actually ordered, per the platform. Stock "
                "movements use THIS, not the import time, so a file uploaded "
                "the next morning still consumes against the right day."
    )
    external_imported_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True,
        comment="When we imported it — kept separate from external_placed_at"
    )
    external_status: Mapped[str | None] = mapped_column(
        String(48), nullable=True, comment="Raw status text from the platform's report"
    )

    idempotency_key: Mapped[str | None] = mapped_column(
        String(128), nullable=True,
        comment="Client-generated key; a retry with the same key returns the "
                 "original order instead of creating a duplicate sale (unique "
                 "per business_id, partial index — see migration 0023)"
    )
    created_by_user_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True), nullable=True,
        comment="Cashier who rang up a POS sale — not FK-enforced, same "
                 "pattern as cancelled_by_user_id"
    )

    # ── Loyalty redemption (Phase: POS redemption, migration 0050) ───────
    # Immutable financial snapshot, same reason total_cents isn't rewritten
    # on a later refund/void: a reprint a month later must show what was
    # actually charged and redeemed at the time, not today's catalogue.
    loyalty_discount_cents: Mapped[int] = mapped_column(
        Integer, default=0, nullable=False,
        comment="Cents discounted off this sale by a redeemed reward — "
                 "already netted into total_cents, never rewritten by a "
                 "later refund/void"
    )
    loyalty_reward_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True), ForeignKey("loyalty_rewards.id", ondelete="SET NULL"),
        nullable=True, index=True,
        comment="Which reward was redeemed, if any — SET NULL on delete so "
                 "removing a reward from the catalogue never rewrites history"
    )
    loyalty_points_redeemed: Mapped[int] = mapped_column(
        Integer, default=0, nullable=False,
        comment="Full points cost of the redeemed reward, even if "
                 "loyalty_discount_cents was clamped below the reward's "
                 "full value — money and ledger must agree on what happened"
    )
    loyalty_reward_name: Mapped[str | None] = mapped_column(
        String(255), nullable=True,
        comment="Snapshot of LoyaltyReward.name at redemption time — a "
                 "reprint must not depend on the FK resolving or the "
                 "reward's current name, same pattern as name_snapshot"
    )

    # ── Split payments (migration 0055) ──────────────────────────────────
    # How much of a refund/void was handed back as physical CASH, for till
    # reconciliation — distinct from refund_amount_cents (the total refund,
    # any method). Set automatically for a legacy single-CASH-method order
    # (same value as refund_amount_cents, preserving today's exact
    # behaviour) and for a VOID (full reversal of the order's own cash
    # allocation(s), always unambiguous); for a PARTIAL refund of a split
    # sale mixing cash and non-cash methods, the caller must state this
    # explicitly (POSRefundRequest.cash_refund_cents) — see
    # routes_pos.py::refund_pos_order's own comment for why this is
    # deliberately NOT auto-computed in that one ambiguous case.
    refund_cash_cents: Mapped[int | None] = mapped_column(
        Integer, nullable=True,
        comment="Portion of this order's refund/void that was physical "
                 "cash. NULL means nothing has been refunded, or the "
                 "refund involved no cash at all."
    )

    # ── Relationships ────────────────────────────────────────────────────
    items = relationship("OrderItem", back_populates="order", lazy="selectin")
    events = relationship("OrderEvent", back_populates="order", lazy="noload")
    # selectin (not the default lazy="select"): close_till/payment-mix
    # analytics/receipts all need this for every order they touch, and a
    # per-order N+1 SELECT here is exactly the class of bug Part 4 of the
    # earlier entitlement-followup audit warned about.
    payment_allocations = relationship(
        "POSPaymentAllocation", back_populates="order", lazy="selectin",
        order_by="POSPaymentAllocation.created_at",
    )

    def __repr__(self) -> str:
        return f"<Order {self.order_number} [{self.status}]>"


class OrderItem(Base, UUIDPrimaryKeyMixin):
    __tablename__ = "order_items"

    order_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), ForeignKey("orders.id", ondelete="CASCADE"),
        nullable=False, index=True,
    )
    business_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), ForeignKey("businesses.id", ondelete="CASCADE"),
        nullable=False,
    )
    menu_item_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True), nullable=True,
        comment="Nullable — menu item may have been deleted (soft delete preserves this)"
    )

    # ── Snapshot at time of order (immutable) ────────────────────────────
    name_snapshot: Mapped[str] = mapped_column(String(255), nullable=False)

    # Phase 8: full pricing breakdown — base + option deltas + add-ons = unit_price
    # Existing rows have base_price_cents = unit_price_cents and adjustments = 0.
    base_price_cents: Mapped[int] = mapped_column(
        Integer, nullable=False, default=0,
        comment="MenuItem.price_cents at order time, before adjustments"
    )
    option_adjustment_cents: Mapped[int] = mapped_column(
        Integer, nullable=False, default=0,
        comment="Sum of selected option price_delta_cents (may be negative)"
    )
    add_on_total_cents: Mapped[int] = mapped_column(
        Integer, nullable=False, default=0,
        comment="Sum of add-on price_cents × quantity for this line item"
    )
    unit_price_cents: Mapped[int] = mapped_column(
        Integer, nullable=False,
        comment="base + option_adjustment + add_on_total (effective per-unit price)"
    )
    quantity: Mapped[int] = mapped_column(Integer, nullable=False)
    line_total_cents: Mapped[int] = mapped_column(Integer, nullable=False)

    # Snapshots for display and audit — these never change after order creation
    options_snapshot: Mapped[dict | None] = mapped_column(
        JSONB, nullable=True,
        comment="Raw {group_name: option_name} dict from LLM (backward compat)"
    )
    selected_options_snapshot: Mapped[list | None] = mapped_column(
        JSONB, nullable=True,
        comment="[{group_id, group_name, option_id, option_name, price_delta_cents}]"
    )
    add_ons_snapshot: Mapped[list | None] = mapped_column(
        JSONB, nullable=True,
        comment="[{add_on_id, name, price_cents, quantity}]"
    )
    removed_ingredients_snapshot: Mapped[list | None] = mapped_column(
        JSONB, nullable=True,
        comment="[{id, name}] — resolved from MenuItem.options_json.removable_ingredients "
                 "at order time, immutable like the other snapshot columns"
    )
    special_instructions: Mapped[str | None] = mapped_column(Text, nullable=True)

    # BUG-0016 fix (migration 0038): True only for a dashboard-typed
    # name+price_cents line with no menu_item_id — a caller-asserted price
    # never checked against the live catalog. False (the default) for every
    # other line: POS orders, WhatsApp bot orders, and dashboard orders that
    # supplied menu_item_id, all of which are resolved and priced
    # server-side via backend/app/pos/pricing.py::resolve_pos_items.
    is_ad_hoc_price: Mapped[bool] = mapped_column(
        Boolean, nullable=False, default=False, server_default="false",
    )

    # ── Relationships ────────────────────────────────────────────────────
    order = relationship("Order", back_populates="items")


class OrderEvent(Base, UUIDPrimaryKeyMixin):
    """Audit trail for order status changes."""
    __tablename__ = "order_events"

    order_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), ForeignKey("orders.id", ondelete="CASCADE"),
        nullable=False, index=True,
    )
    business_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), ForeignKey("businesses.id", ondelete="CASCADE"),
        nullable=False,
    )
    old_status: Mapped[str | None] = mapped_column(String(32), nullable=True)
    new_status: Mapped[str] = mapped_column(String(32), nullable=False)
    changed_by_user_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True), nullable=True
    )
    reason: Mapped[str | None] = mapped_column(Text, nullable=True)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False,
        default=lambda: __import__("datetime").datetime.now(__import__("datetime").timezone.utc),
    )

    # ── Relationships ────────────────────────────────────────────────────
    order = relationship("Order", back_populates="events")
